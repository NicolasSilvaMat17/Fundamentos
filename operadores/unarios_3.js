//!! = descobrir se algo em javascript é avaliado como verdadeiro ou falso
console.log(!!true);
console.log(!!false);

console.log(!!'Texto!');
console.log(!!''); // um texto vazio é avaliado como falso 
console.log(!!' '); // um texto com alguma frase oou espaço em branco é avaliado como verdadeiro

console.log(!!1);
console.log(!!0);
